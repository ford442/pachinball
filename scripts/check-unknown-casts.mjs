#!/usr/bin/env node
/**
 * `as unknown as` ratchet (#489 slice A, extended to all of src/).
 *
 * A double cast through `unknown` switches the type checker off for that expression. Track modules
 * used ~200 of them to reach TrackBuilder's protected members; they now build through the typed
 * TrackBuilderApi, and the rest of src/ was brought to zero after them. Any `as unknown as` under
 * src/ fails (Emscripten's generated declarations excepted). Comments are ignored, so prose may name
 * the pattern. Tests and scripts are out of scope: a test stubbing a host may cast freely.
 *
 * Instead of a double cast: declare the global on `Window` (src/vite-env.d.ts), take a narrower type
 * (`Pick<Host, ...>`), downcast once to an intersection (`x as T & Extra`), or narrow with `in`.
 */
import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ENFORCED_DIRS = ['src/']
/** Emscripten --emit-tsd output; regenerated by `npm run build:wasm`, never edited by hand. */
const IGNORED_DIRS = ['src/wasm/generated/']

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function* tsFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* tsFiles(path)
    else if (/\.tsx?$/.test(entry.name) && !entry.name.endsWith('.d.ts')) yield path
  }
}

/** Blank out comments, keeping newlines so reported line numbers stay right. */
function stripComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, (block) => block.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1')
}

const castPattern = /\bas\s+unknown\s+as\b/g
const hits = []
for (const file of tsFiles(join(root, 'src'))) {
  const rel = relative(root, file).replaceAll('\\', '/')
  if (IGNORED_DIRS.some((dir) => rel.startsWith(dir))) continue
  const code = stripComments(readFileSync(file, 'utf8'))
  for (const match of code.matchAll(castPattern)) {
    const line = code.slice(0, match.index).split('\n').length
    hits.push({ file: rel, line })
  }
}

if (hits.length > 0) {
  console.error(`[unknown-casts] ${hits.length} \`as unknown as\` cast(s) under ${ENFORCED_DIRS.join(', ')}:\n`)
  for (const h of hits) console.error(`  ${h.file}:${h.line}`)
  console.error('\nTrack modules build through TrackBuilderApi (src/adventure/track-builder-api.ts); extend it instead.')
  console.error('Elsewhere: a Window global in src/vite-env.d.ts, a Pick<> of the host, or one downcast to `T & Extra`.')
  process.exit(1)
}

console.log(`[unknown-casts] OK — src/ holds no \`as unknown as\`.`)
