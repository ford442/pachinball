#!/usr/bin/env node
/**
 * `as unknown as` ratchet (#489 slice A).
 *
 * A double cast through `unknown` switches the type checker off for that expression. Track modules
 * used ~200 of them to reach TrackBuilder's protected members; they now build through the typed
 * TrackBuilderApi, and ENFORCED_DIRS hold that at zero. Elsewhere in src/ the count is reported as
 * backlog, not a failure. Comments are ignored, so prose may name the pattern.
 *
 * To extend the ratchet: remove a directory's casts, then add it to ENFORCED_DIRS.
 */
import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ENFORCED_DIRS = ['src/adventure/']
/** Emscripten --emit-tsd output; regenerated by `npm run build:wasm`, never edited by hand. */
const IGNORED_DIRS = ['src/wasm/generated/']

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

function* tsFiles(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* tsFiles(path)
    else if (/\.tsx?$/.test(entry.name) && !entry.name.endsWith('.d.ts')) yield path
  }
}

/** Blank out comments, keeping newlines so reported line numbers stay right. */
function stripComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, (block) => block.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:'"`\\])\/\/[^\n]*/g, '$1')
}

const castPattern = /\bas\s+unknown\s+as\b/g
const hits = []
for (const file of tsFiles(join(root, 'src'))) {
  const rel = relative(root, file).replaceAll('\\', '/')
  if (IGNORED_DIRS.some((dir) => rel.startsWith(dir))) continue
  const code = stripComments(readFileSync(file, 'utf8'))
  for (const match of code.matchAll(castPattern)) {
    const line = code.slice(0, match.index).split('\n').length
    hits.push({ file: rel, line })
  }
}

const enforced = hits.filter((h) => ENFORCED_DIRS.some((dir) => h.file.startsWith(dir)))
if (enforced.length > 0) {
  console.error(`[unknown-casts] ${enforced.length} \`as unknown as\` cast(s) in directories held to zero:\n`)
  for (const h of enforced) console.error(`  ${h.file}:${h.line}`)
  console.error(`\nEnforced: ${ENFORCED_DIRS.join(', ')}`)
  console.error('Track modules build through TrackBuilderApi (src/adventure/track-builder-api.ts); extend it instead.')
  process.exit(1)
}

const todo = new Map()
for (const h of hits) {
  const dir = h.file.split('/').slice(0, 2).join('/')
  todo.set(dir, (todo.get(dir) ?? 0) + 1)
}
const remaining = [...todo.entries()].sort((a, b) => b[1] - a[1]).map(([dir, n]) => `${dir} ${n}`).join(', ')
console.log(`[unknown-casts] OK — ${ENFORCED_DIRS.join(', ')} hold no \`as unknown as\`.`)
console.log(`[unknown-casts] ratchet backlog: ${hits.length} cast(s)${remaining ? ` (${remaining})` : ''}`)
